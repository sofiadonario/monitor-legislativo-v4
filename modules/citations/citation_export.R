#' Export to EndNote XML Format
#' @param parsed_metadata_list List of parsed metadata objects
#' @param filename Output filename (optional)
#' @return EndNote XML string
export_endnote_xml <- function(parsed_metadata_list, filename = NULL) {
  if (!requireNamespace("xml2", quietly = TRUE)) {
    cat("⚠️ xml2 package required for EndNote XML export\n")
    return(NULL)
  }
  
  if (!is.list(parsed_metadata_list)) {
    parsed_metadata_list <- list(parsed_metadata_list)
  }
  
  # Create XML structure
  xml_doc <- xml2::xml_new_root("xml")
  records_node <- xml2::xml_add_child(xml_doc, "records")
  
  for (i in seq_along(parsed_metadata_list)) {
    metadata <- parsed_metadata_list[[i]]
    record_node <- generate_endnote_record(records_node, metadata, i)
  }
  
  xml_text <- as.character(xml_doc)
  
  # Save to file if filename provided
  if (!is.null(filename)) {
    xml2::write_xml(xml_doc, filename)
    cat("✅ EndNote XML exported to:", filename, "\n")
  }
  
  return(xml_text)
}

#' Generate EndNote XML Record
#' @param parent_node Parent XML node
#' @param metadata Parsed metadata object
#' @param index Record index
#' @return XML record node
generate_endnote_record <- function(parent_node, metadata, index) {
  if (!requireNamespace("xml2", quietly = TRUE)) return(NULL)
  
  record_node <- xml2::xml_add_child(parent_node, "record")
  
  # Add database info
  database_node <- xml2::xml_add_child(record_node, "database", 
                                      name = "Monitor Legislativo", 
                                      path = "monitor_legislativo.enl")
  
  # Add source info
  source_app_node <- xml2::xml_add_child(record_node, "source-app", 
                                        name = "Monitor Legislativo Citation System",
                                        version = "1.0")
  
  # Add record number
  rec_number_node <- xml2::xml_add_child(record_node, "rec-number", as.character(index))
  
  # Add reference type (Bill/Law for legislation)
  ref_type_node <- xml2::xml_add_child(record_node, "ref-type", name = "Bill")
  
  # Add contributors (authors/authorities)
  contributors_node <- xml2::xml_add_child(record_node, "contributors")
  authors_node <- xml2::xml_add_child(contributors_node, "authors")
  
  if (!isTRUE(is.null(metadata$authority)) && metadata$authority != "") {
    author_node <- xml2::xml_add_child(authors_node, "author")
    xml2::xml_add_child(author_node, "style", face = "normal", font = "default", size = "100%", 
                       metadata$authority)
  }
  
  # Add titles
  titles_node <- xml2::xml_add_child(record_node, "titles")
  
  if (!isTRUE(is.null(metadata$original_title)) && metadata$original_title != "") {
    title_node <- xml2::xml_add_child(titles_node, "title")
    xml2::xml_add_child(title_node, "style", face = "normal", font = "default", size = "100%",
                       metadata$original_title)
  }
  
  # Add dates
  dates_node <- xml2::xml_add_child(record_node, "dates")
  if (!isTRUE(is.null(metadata$year)) && metadata$year != "") {
    year_node <- xml2::xml_add_child(dates_node, "year")
    xml2::xml_add_child(year_node, "style", face = "normal", font = "default", size = "100%",
                       metadata$year)
  }
  
  # Add publisher (jurisdiction)
  publisher_node <- xml2::xml_add_child(record_node, "publisher")
  if (!isTRUE(is.null(metadata$jurisdiction)) && metadata$jurisdiction != "") {
    xml2::xml_add_child(publisher_node, "style", face = "normal", font = "default", size = "100%",
                       metadata$jurisdiction)
  }
  
  # Add URLs
  urls_node <- xml2::xml_add_child(record_node, "urls")
  if (!isTRUE(is.null(metadata$url)) && metadata$url != "") {
    related_urls_node <- xml2::xml_add_child(urls_node, "related-urls")
    url_node <- xml2::xml_add_child(related_urls_node, "url")
    xml2::xml_add_child(url_node, "style", face = "normal", font = "default", size = "100%",
                       metadata$url)
  }
  
  # Add custom fields
  custom_node <- xml2::xml_add_child(record_node, "custom7")  # Document type
  if (!isTRUE(is.null(metadata$document_type)) && metadata$document_type != "") {
    xml2::xml_add_child(custom_node, "style", face = "normal", font = "default", size = "100%",
                       metadata$document_type)
  }
  
  return(record_node)
}

