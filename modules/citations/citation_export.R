#' Export Multiple Formats Simultaneously
#' @param parsed_metadata_list List of parsed metadata objects
#' @param output_dir Output directory
#' @param base_filename Base filename (without extension)
#' @param formats Vector of formats to export
#' @return List of export results
bulk_export_citations <- function(parsed_metadata_list, 
                                 output_dir = "exports", 
                                 base_filename = "brazilian_legislative_citations",
                                 formats = c("bibtex", "ris", "endnote", "abnt_plain", "apa_plain")) {
  
  # Create output directory if it doesn't exist
  if (!dir.exists(output_dir)) {
    dir.create(output_dir, recursive = TRUE)
    cat("📁 Created output directory:", output_dir, "\n")
  }
  
  export_results <- list()
  
  for (format in formats) {
    tryCatch({
      if (format == "bibtex") {
        filename <- file.path(output_dir, paste0(base_filename, ".bib"))
        result <- export_bibtex(parsed_metadata_list, filename)
        export_results[[format]] <- list(success = TRUE, file = filename, content = result)
        
      } else if (format == "ris") {
        filename <- file.path(output_dir, paste0(base_filename, ".ris"))
        result <- export_ris(parsed_metadata_list, filename)
        export_results[[format]] <- list(success = TRUE, file = filename, content = result)
        
      } else if (format == "endnote") {
        filename <- file.path(output_dir, paste0(base_filename, ".xml"))
        result <- export_endnote_xml(parsed_metadata_list, filename)
        export_results[[format]] <- list(success = TRUE, file = filename, content = result)
        
      } else if (format == "abnt_plain") {
        filename <- file.path(output_dir, paste0(base_filename, "_abnt.txt"))
        result <- export_plain_text(parsed_metadata_list, "abnt", "pt", filename)
        export_results[[format]] <- list(success = TRUE, file = filename, content = result)
        
      } else if (format == "apa_plain") {
        filename <- file.path(output_dir, paste0(base_filename, "_apa.txt"))
        result <- export_plain_text(parsed_metadata_list, "apa", "en", filename)
        export_results[[format]] <- list(success = TRUE, file = filename, content = result)
        
      } else {
        export_results[[format]] <- list(success = FALSE, error = paste("Unsupported format:", format))
      }
      
    }, error = function(e) {
      export_results[[format]] <- list(success = FALSE, error = e$message)
      cat("❌ Export failed for", format, ":", e$message, "\n")
    })
  }
  
  # Summary
  successful_exports <- sum(sapply(export_results, function(x) x$success))
  cat("✅ Bulk export completed:", successful_exports, "of", length(formats), "formats exported\n")
  
  return(export_results)
}

