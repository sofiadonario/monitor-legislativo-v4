#' Export to BibTeX Format
#' @param parsed_metadata_list List of parsed metadata objects
#' @param filename Output filename (optional)
#' @return BibTeX formatted string
export_bibtex <- function(parsed_metadata_list, filename = NULL) {
  if (!is.list(parsed_metadata_list)) {
    parsed_metadata_list <- list(parsed_metadata_list)
  }
  
  bibtex_entries <- c()
  
  for (i in seq_along(parsed_metadata_list)) {
    metadata <- parsed_metadata_list[[i]]
    bibtex_entry <- generate_bibtex_entry(metadata, i)
    bibtex_entries <- c(bibtex_entries, bibtex_entry)
  }
  
  # Add BibTeX header comment
  bibtex_content <- c(
    "% BibTeX entries for Brazilian Legislative Documents",
    "% Generated by Monitor Legislativo Citation System",
    paste("% Generated on:", Sys.time()),
    "",
    bibtex_entries
  )
  
  bibtex_text <- paste(bibtex_content, collapse = "\n")
  
  # Save to file if filename provided
  if (!is.null(filename)) {
    writeLines(bibtex_text, filename, useBytes = TRUE)
    cat("✅ BibTeX exported to:", filename, "\n")
  }
  
  return(bibtex_text)
}

#' Generate Single BibTeX Entry
#' @param metadata Parsed metadata object
#' @param index Entry index for citation key
#' @return BibTeX entry string
generate_bibtex_entry <- function(metadata, index) {
  if (is.null(metadata)) return("")
  
  # Generate citation key
  citation_key <- generate_bibtex_key(metadata, index)
  
  # Determine entry type
  entry_type <- determine_bibtex_entry_type(metadata)
  
  # Build BibTeX entry
  entry_lines <- c(
    paste0("@", entry_type, "{", citation_key, ",")
  )
  
  # Add required fields
  if (!isTRUE(is.null(metadata$original_title)) && metadata$original_title != "") {
    title_clean <- escape_bibtex_special_chars(metadata$original_title)
    entry_lines <- c(entry_lines, paste0("  title = {", title_clean, "},"))
  }
  
  if (!isTRUE(is.null(metadata$authority)) && metadata$authority != "") {
    author_clean <- escape_bibtex_special_chars(metadata$authority)
    entry_lines <- c(entry_lines, paste0("  author = {", author_clean, "},"))
  }
  
  if (!isTRUE(is.null(metadata$year)) && metadata$year != "") {
    entry_lines <- c(entry_lines, paste0("  year = {", metadata$year, "},"))
  }
  
  # Add document type
  if (!isTRUE(is.null(metadata$document_type)) && metadata$document_type != "") {
    type_clean <- escape_bibtex_special_chars(metadata$document_type)
    entry_lines <- c(entry_lines, paste0("  type = {", type_clean, "},"))
  }
  
  # Add document number
  if (!isTRUE(is.null(metadata$document_number)) && metadata$document_number != "") {
    entry_lines <- c(entry_lines, paste0("  number = {", metadata$document_number, "},"))
  }
  
  # Add jurisdiction
  if (!isTRUE(is.null(metadata$jurisdiction)) && metadata$jurisdiction != "") {
    entry_lines <- c(entry_lines, paste0("  address = {", metadata$jurisdiction, "},"))
  }
  
  # Add URL
  if (!isTRUE(is.null(metadata$url)) && metadata$url != "") {
    entry_lines <- c(entry_lines, paste0("  url = {", metadata$url, "},"))
  }
  
  # Add URN
  if (!isTRUE(is.null(metadata$urn)) && metadata$urn != "") {
    entry_lines <- c(entry_lines, paste0("  note = {URN: ", metadata$urn, "},"))
  }
  
  # Add access date
  entry_lines <- c(entry_lines, paste0("  urldate = {", format(Sys.Date(), "%Y-%m-%d"), "}"))
  
  # Close entry (remove last comma and add closing brace)
  if (length(entry_lines) > 1) {
    last_line <- entry_lines[length(entry_lines)]
    entry_lines[length(entry_lines)] <- stringr::str_remove(last_line, ",$")
  }
  entry_lines <- c(entry_lines, "}")
  
  return(paste(entry_lines, collapse = "\n"))
}

#' Generate BibTeX Citation Key
#' @param metadata Parsed metadata
#' @param index Entry index
#' @return Citation key string
generate_bibtex_key <- function(metadata, index) {
  key_parts <- c()
  
  # Use authority abbreviation
  if (!isTRUE(is.null(metadata$authority)) && metadata$authority != "") {
    if (grepl("BRASIL", metadata$authority)) {
      key_parts <- c(key_parts, "brasil")
    } else if (grepl("ESTADO", metadata$authority)) {
      key_parts <- c(key_parts, "estado")
    } else if (grepl("MUNICÍPIO", metadata$authority)) {
      key_parts <- c(key_parts, "municipio")
    } else {
      # Use first word of authority
      auth_word <- stringr::str_extract(tolower(metadata$authority), "^\\w+")
      key_parts <- c(key_parts, auth_word)
    }
  }
  
  # Add year
  if (!isTRUE(is.null(metadata$year)) && metadata$year != "") {
    key_parts <- c(key_parts, metadata$year)
  }
  
  # Add document number if available
  if (!isTRUE(is.null(metadata$document_number)) && metadata$document_number != "") {
    # Clean number for use in key
    number_clean <- stringr::str_remove_all(metadata$document_number, "[^\\d]")
    if (number_clean != "" && nchar(number_clean) <= 6) {
      key_parts <- c(key_parts, paste0("n", number_clean))
    }
  }
  
  # Fallback to index if no other parts
  if (length(key_parts) == 0) {
    key_parts <- c("doc", sprintf("%03d", index))
  }
  
  return(paste(key_parts, collapse = "_"))
}

#' Determine BibTeX Entry Type
#' @param metadata Parsed metadata
#' @return BibTeX entry type
determine_bibtex_entry_type <- function(metadata) {
  if (is.null(metadata$document_type)) return("misc")
  
  doc_type <- tolower(metadata$document_type)
  
  if (grepl("lei|law", doc_type)) return("legislation")
  if (grepl("decreto|decree", doc_type)) return("legislation") 
  if (grepl("constituição|constitution", doc_type)) return("legislation")
  if (grepl("resolução|resolution", doc_type)) return("techreport")
  if (grepl("portaria|ordinance", doc_type)) return("techreport")
  if (grepl("instrução|instruction", doc_type)) return("techreport")
  
  return("misc")
}

#' Escape BibTeX Special Characters
#' @param text Text to escape
#' @return Escaped text
escape_bibtex_special_chars <- function(text) {
  if (isTRUE(is.null(text)) || text == "") return("")
  
  # Escape BibTeX special characters
  text <- gsub("\\\\", "\\\\textbackslash{}", text)  # Backslash first
  text <- gsub("\\{", "\\\\{", text)
  text <- gsub("\\}", "\\\\}", text)
  text <- gsub("\\$", "\\\\$", text)
  text <- gsub("&", "\\\\&", text)
  text <- gsub("%", "\\\\%", text)
  text <- gsub("#", "\\\\#", text)
  text <- gsub("\\^", "\\\\textasciicircum{}", text)
  text <- gsub("_", "\\\\_", text)
  text <- gsub("~", "\\\\textasciitilde{}", text)
  
  return(text)
}

