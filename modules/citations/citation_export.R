#' Export to RIS Format
#' @param parsed_metadata_list List of parsed metadata objects
#' @param filename Output filename (optional)
#' @return RIS formatted string
export_ris <- function(parsed_metadata_list, filename = NULL) {
  if (!is.list(parsed_metadata_list)) {
    parsed_metadata_list <- list(parsed_metadata_list)
  }
  
  ris_entries <- c()
  
  for (i in seq_along(parsed_metadata_list)) {
    metadata <- parsed_metadata_list[[i]]
    ris_entry <- generate_ris_entry(metadata)
    ris_entries <- c(ris_entries, ris_entry, "")  # Add empty line between entries
  }
  
  ris_text <- paste(ris_entries, collapse = "\n")
  
  # Save to file if filename provided
  if (!is.null(filename)) {
    writeLines(ris_text, filename, useBytes = TRUE)
    cat("✅ RIS exported to:", filename, "\n")
  }
  
  return(ris_text)
}

#' Generate Single RIS Entry
#' @param metadata Parsed metadata object
#' @return RIS entry string
generate_ris_entry <- function(metadata) {
  if (is.null(metadata)) return("")
  
  # Determine RIS type
  ris_type <- determine_ris_type(metadata)
  
  ris_lines <- c(
    paste0("TY  - ", ris_type)  # Type of reference
  )
  
  # Add title
  if (!isTRUE(is.null(metadata$original_title)) && metadata$original_title != "") {
    ris_lines <- c(ris_lines, paste0("TI  - ", metadata$original_title))
  }
  
  # Add author/authority
  if (!isTRUE(is.null(metadata$authority)) && metadata$authority != "") {
    ris_lines <- c(ris_lines, paste0("AU  - ", metadata$authority))
  }
  
  # Add publication year
  if (!isTRUE(is.null(metadata$year)) && metadata$year != "") {
    ris_lines <- c(ris_lines, paste0("PY  - ", metadata$year))
  }
  
  # Add publication date
  if (!isTRUE(is.null(metadata$publication_date)) && metadata$publication_date != "") {
    ris_lines <- c(ris_lines, paste0("DA  - ", metadata$publication_date))
  }
  
  # Add document type as note
  if (!isTRUE(is.null(metadata$document_type)) && metadata$document_type != "") {
    ris_lines <- c(ris_lines, paste0("N1  - ", metadata$document_type))
  }
  
  # Add document number
  if (!isTRUE(is.null(metadata$document_number)) && metadata$document_number != "") {
    ris_lines <- c(ris_lines, paste0("VL  - ", metadata$document_number))
  }
  
  # Add jurisdiction as publisher
  if (!isTRUE(is.null(metadata$jurisdiction)) && metadata$jurisdiction != "") {
    ris_lines <- c(ris_lines, paste0("PB  - ", metadata$jurisdiction))
  }
  
  # Add URL
  if (!isTRUE(is.null(metadata$url)) && metadata$url != "") {
    ris_lines <- c(ris_lines, paste0("UR  - ", metadata$url))
  }
  
  # Add URN as note
  if (!isTRUE(is.null(metadata$urn)) && metadata$urn != "") {
    ris_lines <- c(ris_lines, paste0("N1  - URN: ", metadata$urn))
  }
  
  # End of record
  ris_lines <- c(ris_lines, "ER  - ")
  
  return(paste(ris_lines, collapse = "\n"))
}

#' Determine RIS Type
#' @param metadata Parsed metadata
#' @return RIS type code
determine_ris_type <- function(metadata) {
  if (is.null(metadata$document_type)) return("GEN")  # Generic
  
  doc_type <- tolower(metadata$document_type)
  
  if (grepl("lei|law|decreto|decree|constituição|constitution", doc_type)) return("BILL")
  if (grepl("resolução|resolution|portaria|ordinance", doc_type)) return("RPRT")  # Report
  if (grepl("instrução|instruction", doc_type)) return("RPRT")
  
  return("GEN")  # Generic fallback
}

