#' Export to Plain Text Format
#' @param parsed_metadata_list List of parsed metadata objects
#' @param format Citation format ("abnt", "apa", "vancouver", "bluebook")
#' @param language Language for citations
#' @param filename Output filename (optional)
#' @return Plain text citations
export_plain_text <- function(parsed_metadata_list, format = "abnt", language = "pt", filename = NULL) {
  if (!is.list(parsed_metadata_list)) {
    parsed_metadata_list <- list(parsed_metadata_list)
  }
  
  # Load citation templates if not available
  if (!exists("format_abnt_citation")) {
    if (file.exists("modules/citations/citation_templates.R")) {
      source("modules/citations/citation_templates.R")
    }
  }
  
  citations <- c()
  
  # Add header
  if (format == "abnt") {
    if (language == "pt") {
      citations <- c(citations, "REFERÊNCIAS", "")
    } else {
      citations <- c(citations, "REFERENCES", "")
    }
  } else {
    citations <- c(citations, paste("CITATIONS -", toupper(format)), "")
  }
  
  # Generate citations
  for (i in seq_along(parsed_metadata_list)) {
    metadata <- parsed_metadata_list[[i]]
    
    if (exists(paste0("format_", format, "_citation"))) {
      citation_func <- get(paste0("format_", format, "_citation"))
      
      if (format == "vancouver") {
        citation <- citation_func(metadata, i)
      } else {
        citation <- citation_func(metadata, language)
      }
    } else {
      citation <- paste("Unsupported format:", format)
    }
    
    citations <- c(citations, citation, "")
  }
  
  plain_text <- paste(citations, collapse = "\n")
  
  # Save to file if filename provided
  if (!is.null(filename)) {
    writeLines(plain_text, filename, useBytes = TRUE)
    cat("✅ Plain text exported to:", filename, "\n")
  }
  
  return(plain_text)
}

